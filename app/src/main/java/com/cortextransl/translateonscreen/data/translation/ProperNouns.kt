    fun override(text: String, target: String): String? {
        val trimmed = text.trim()
        if (trimmed.startsWith("#") && trimmed.none { it.isWhitespace() }) return trimmed
        val key = trimmed.lowercase(Locale.US)
            .replace(Regex("[\\u2122\\u00ae\\.:,!]"), "")
            .trim()
        if (target.startsWith("ar")) {
            arabic[key]?.let { return it }
        }
        // For other targets only pass through real brand names (entries kept in
        // Latin script), never generic UI words like "search" or "install".
        val value = arabic[key] ?: return null
        return if (value.any { it in 'A'..'Z' || it in 'a'..'z' }) trimmed else null
    }

    /**
     * Check if a single word or brand name exists in our dictionary to prevent
     * offline ML Kit from butchering it (e.g. Steam -> بخار).
     */
    fun lookupArabic(word: String): String? {
        val key = word.lowercase(Locale.US).replace(Regex("[\\u2122\\u00ae\\.:,!]"), "").trim()
        return arabic[key]
    }
